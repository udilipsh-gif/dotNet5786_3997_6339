    /// <remarks>
    /// This method collects the following information from the user:
    /// <list type="bullet">
    /// <item><description>Courier ID</description></item>
    /// <item><description>Name</description></item>
    /// <item><description>Phone number</description></item>
    /// <item><description>Email address</description></item>
    /// <item><description>Password (required, cannot be empty)</description></item>
    /// <item><description>Type of shipment (CAR=0, MOTORCYCLE=1, BICYCLE=2, FOOT=3)</description></item>
    /// <item><description>Maximum delivery distance in kilometers</description></item>
    /// </list>
    /// The courier is automatically marked as active, and the working since date is set to the current system clock time.
    /// </remarks>
    private static Courier createCourier()
    {


        Console.WriteLine("Creating a new courier...");

        Console.Write("Enter ID of courier: ");
        int id = GetIntInput();

        Console.Write("Enter Name: ");
        string name = Console.ReadLine() ?? string.Empty;

        Console.Write("Enter Phone: ");
        string phone = Console.ReadLine() ?? string.Empty;

        Console.Write("Enter Email: ");
        string email = Console.ReadLine() ?? string.Empty;

        string password = string.Empty;
        while (password == string.Empty)
        {
            Console.Write("Enter Password: ");
            password = Console.ReadLine() ?? string.Empty;
        }

        Console.Write("Enter Type Shipment (0=CAR, 1=MOTORCYCLE, 2=BICYCLE, 3=FOOT): ");
        int typeShipmentInput = GetIntInput();

        Console.Write("Enter Max Distance Delivery (in km): ");
        string maxDistanceInput = Console.ReadLine() ?? "0";
        double maxDistanceDelivery = double.Parse(maxDistanceInput);

        return new Courier
        {
            Id = id,
            Name = name,
            Phone = phone,
            Email = email,
            Password = password,
            Active = true,
            MaxDistanceDelivery = maxDistanceDelivery,
            TypeShipment = (TheTypeShipment)typeShipmentInput,
            WorkingSince = s_bl.Admin.GetClock(),
            DeliveryOnTime = 0,
            DeliveryLate = 0,

        };

    }
