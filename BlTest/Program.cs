    /// <summary>
    /// Prompts the user to enter an integer value from the console.
    /// </summary>
    /// <returns>A valid integer entered by the user.</returns>
    /// <remarks>
    /// This method continuously prompts the user until a valid integer is entered.
    /// If the input cannot be parsed as an integer, displays an error message and requests new input.
    /// </remarks>
    public static int GetIntInput()
    {
        int result;
        while (true)
        {
            if (int.TryParse(Console.ReadLine(), out result))
            {
                return result;
            }
            Console.WriteLine("Invalid input. Please enter a valid integer.");
        }
    }

