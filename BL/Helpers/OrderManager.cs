    {
        throw new BO.BlInvalidOperationException("Order cannot be deleted. Use Cancel instead.");
    }

    /// <summary>
    /// Retrieves all orders from the system with optional filtering and sorting.
    /// </summary>
    /// <param name="filter">The field to filter by, or null for no filtering.</param>
    /// <param name="filterValue">The value to match for the specified filter field.</param>
    /// <param name="orderBy">The field to sort by (default is OrderStatus).</param>
    /// <returns>A list of orders in list view format, filtered and sorted as specified.</returns>
    /// <remarks>
    /// Converts data layer orders to business logic OrderInList objects,
    /// applies the specified filter predicate, and sorts by the requested field.
    /// </remarks>
    public static List<BO.OrderInList> ReadAll(
        BO.OrderInListField? filter,
        object? filterValue,
        BO.OrderInListField? orderBy = BO.OrderInListField.OrderStatus)
    {
        Func<BO.OrderInList, bool> filterPredicate = s_getFilterPredicate(filter, filterValue);
        return ReadAll(filterPredicate, orderBy);
    }

    /// <summary>
    /// Retrieves all orders from the system with a custom filter predicate.
    /// </summary>
    /// <param name="customPredicate">Custom filter function, or null to include all orders.</param>
    /// <param name="orderBy">The field to sort by (default is OrderId).</param>
    /// <returns>A list of orders in list view format, filtered and sorted as specified.</returns>
    public static List<BO.OrderInList> ReadAll(
        Func<BO.OrderInList, bool>? customPredicate = null,
        BO.OrderInListField? orderBy = BO.OrderInListField.OrderId)
    {
        // Pre-fetch all deliveries and group by order ID for efficient lookup
        var deliveriesMap = s_dal.Delivery.ReadAll()
            .GroupBy(d => d.OrderId)
            .ToDictionary(g => g.Key, g => g.OrderByDescending(d => d.Id).ToList());

        Func<BO.OrderInList, bool> filter = customPredicate ?? (_ => true);
        Func<BO.OrderInList, object> sortSelector = s_getSortSelector(orderBy);

        var query = from doOrder in s_dal.Order.ReadAll()
                    let boOrder = s_convertToBoOrderOptimized(doOrder, deliveriesMap)
                    where filter(boOrder)
                    orderby sortSelector(boOrder)
                    select boOrder;

        return [.. query];
    }


    /// <summary>
    /// Cancels an existing order based on its current status.
    /// </summary>
    /// <param name="orderId">The unique identifier of the order to cancel.</param>
    /// <exception cref="BO.BlDoesNotExistException">
    /// Thrown when the order or associated delivery is not found.
    /// </exception>
    /// <exception cref="BO.BlInvalidOperationException">
    /// Thrown when the order cannot be cancelled due to its current status.
    /// </exception>
    /// <remarks>
    /// Cancellation behavior depends on the order status:
    /// <list type="bullet">
    ///   <item><description>OPEN/REFUSED: Creates a cancellation delivery record</description></item>
    ///   <item><description>DELIVERING: Updates the current delivery with cancellation status and notifies courier via email</description></item>
    ///   <item><description>COMPLETED/CANCELLED: Cannot be cancelled (throws exception)</description></item>
    /// </list>
    /// </remarks>
    public static void Cancel(int orderId)
    {
        DO.Order doOrder = s_dal.Order.Read(orderId)
            ?? throw new BO.BlDoesNotExistException("Order not found");

        Action action = doOrder.OrderStatus switch
        {
            DO.OrderStatus.COMPLETED => throw new BO.BlInvalidOperationException("Cannot cancel a completed order."),
            DO.OrderStatus.CONCELLED => throw new BO.BlInvalidOperationException("Order is already cancelled."),
            DO.OrderStatus.OPEN or DO.OrderStatus.REFUSED => () => s_cancelOpenOrder(doOrder),
            DO.OrderStatus.DELIVERING => () => s_cancelDeliveringOrder(doOrder, orderId),
            _ => throw new BO.BlInvalidOperationException("Invalid order status.")
        };

        action();
        Observer.NotifyItemUpdated(orderId);
        Observer.NotifyListUpdated();
    }

    /// <summary>
    /// Assigns a courier to an open order, initiating the delivery process.
    /// </summary>
    /// <param name="courierId">The unique identifier of the courier to assign.</param>
    /// <param name="orderId">The unique identifier of the order to assign.</param>
    /// <exception cref="BO.BlDoesNotExistException">
    /// Thrown when the order or courier is not found.
    /// </exception>
    /// <exception cref="BO.BlInvalidOperationException">
    /// Thrown when the order is not in OPEN or REFUSED status.
    /// </exception>
    /// <remarks>
    /// Creates a new delivery record linking the courier to the order and updates
    /// the order status to DELIVERING. Only orders with OPEN or REFUSED status can be selected.
    /// </remarks>
    public static void StartDelivery(int courierId, int orderId)
    {
        DO.Order doOrder = s_dal.Order.Read(orderId)
            ?? throw new BO.BlDoesNotExistException("Order not found");

        DO.Courier? doCourier = s_dal.Courier.Read(courierId)
            ?? throw new BO.BlDoesNotExistException("Courier not found");

        // Validate order status without expensive full conversion
        BO.OrderStatus currentStatus = Tools.s_getOrderStatus(doOrder);

        if (currentStatus is not BO.OrderStatus.OPEN)
            throw new BO.BlInvalidOperationException("Order is not open for selection");

        DeliveryManager.Create(doOrder, doCourier);
    }

    /// <summary>
    /// Retrieves all completed deliveries for a specific courier with optional filtering and sorting.
    /// </summary>
    /// <param name="courierId">The unique identifier of the courier.</param>
    /// <param name="filter">Optional filter for order type, or null to include all types.</param>
    /// <param name="sort">The field to sort the results by.</param>
    /// <returns>
    /// A list of closed delivery records showing delivery outcomes, distances, times, and final statuses.
    /// Results are filtered to show only one delivery per order (the most recent).
    /// </returns>
    /// <exception cref="BO.BlDoesNotExistException">Thrown when the courier is not found.</exception>
    /// <remarks>
    /// Only returns deliveries that have ended (EndDelivery is not null).
    /// Results are deduplicated by OrderId to show only the most recent delivery attempt for each order.
    /// </remarks>
    public static List<BO.ClosedDeliveryInList> GetClosed(
        int courierId,
        BO.TypeOfOrder? filter,
        BO.ClosedDeliveryInListField? sort)
    {
        DO.Courier? courier = s_dal.Courier.Read(courierId)
            ?? throw new BO.BlDoesNotExistException("Courier not found");

        var query = from doDelivery in s_dal.Delivery.ReadAll(d => d.CourierId == courierId && d.EndDelivery != null)
                    let order = s_dal.Order.Read(doDelivery.OrderId)
                    where order != null && (filter == null || (BO.TypeOfOrder)order.TypeOfOrder == filter)
                    select new BO.ClosedDeliveryInList
                    {
                        DeliveryId = doDelivery.Id,
                        OrderId = order.Id,
                        OrderType = (BO.TypeOfOrder)order.TypeOfOrder,
                        Address = order.Addres,
                        ShipmentType = (BO.TheTypeShipment)doDelivery.TypeShipment,
                        ActualDistens = GoogleMapsService.GetActualDistance(order.Addres, (BO.TheTypeShipment)courier.TypeShipment),
                        DelyveryTime = (TimeSpan)(doDelivery.TimeEndDelivery! - doDelivery.OrderDate),
                        EndDelivery = (BO.EndDelivery)doDelivery.EndDelivery!
                    };

        var uniqueQuery = query.DistinctBy(x => x.OrderId);

        return [.. s_sortClosedDeliveries(uniqueQuery, sort)];
    }

    /// <summary>
    /// Retrieves all open orders available for a specific courier to deliver.
    /// </summary>
    /// <param name="courierId">The unique identifier of the courier.</param>
    /// <param name="filter">Optional filter for order type, or null to include all types.</param>
    /// <param name="sort">The field to sort the results by.</param>
    /// <returns>
    /// A list of open orders within the courier's maximum delivery distance,
    /// including distance calculations, time constraints, and schedule status.
    /// </returns>
    /// <exception cref="BO.BlDoesNotExistException">Thrown when the courier is not found.</exception>
    /// <remarks>
    /// Only returns orders with OPEN status that are within the courier's
    /// maximum delivery distance capability and match the courier's vehicle capabilities.
    /// Results can be filtered by order type and sorted by various fields.
    /// </remarks>
    public static List<BO.OpenOrderInList> GetOpen(
        int courierId,
        BO.TypeOfOrder? filter,
        BO.OpenOrderInListField? sort)
    {
        DO.Courier doCourier = s_dal.Courier.Read(courierId)
            ?? throw new BO.BlDoesNotExistException("Courier not found");

        var permittedOrders = s_getPermittedOrderTypes(doCourier.TypeShipment);

        Func<DO.Order, bool> orderFilter = order =>
            permittedOrders.Contains(order.TypeOfOrder) &&
            (filter == null || order.TypeOfOrder == (DO.TypeOfOrder)filter);

        double? storLet = AdminManager.GetConfig().Latitude;
        double? storLon = AdminManager.GetConfig().Longitude;
        double? maxDelivery = doCourier.MaxDistanceDelivery;

        Func<DO.Order, bool> permittedDistens = order =>
        {
            if(storLet is double let && storLon is double lon && maxDelivery is double max)
            {
                return Tools.GetDistance(order.Latitude, order.Longitude, let, lon) <= max;
            }
            else
                return true;
        };


        var query = from doOrder in s_dal.Order.ReadAll(o => o.OrderStatus == DO.OrderStatus.OPEN)
                    where (orderFilter(doOrder) && permittedDistens(doOrder))
                    let maxDeliveryTime = doOrder.OrderDate + AdminManager.GetConfig().MaxDeliveryTime
                    let distance = GoogleMapsService.GetActualDistance(doOrder.Addres, (BO.TheTypeShipment)doCourier.TypeShipment)
                    select new BO.OpenOrderInList
                    {
                        OrderId = doOrder.Id,
                        TypeOfOrder = (BO.TypeOfOrder)doOrder.TypeOfOrder,
                        Weight = doOrder.Weight,
                        Address = doOrder.Addres,
                        DistanceKm = doOrder.DistanceKm ?? 0,
                        ActualDistance = distance,
                        EstimatedDeliveryTime = Tools.GetEstimatedDeliveryTime((BO.TheTypeShipment)doCourier.TypeShipment, distance ?? 0),
                        ScheduleStatus = Tools.GetScheduleStatus(doOrder),
                        TimeLeftForDelivery = maxDeliveryTime - AdminManager.Now,
                        MaxDeliveryTime = maxDeliveryTime
                    };

        return [.. s_sortOpenOrders(query, sort)];
    }

    /// <summary>
    /// Validates all required fields of an order.
    /// </summary>
    /// <param name="order">The order to validate.</param>
    /// <exception cref="BO.BlInvalidValueException">Thrown when any required field is invalid.</exception>
    private static void s_validateOrderFields(BO.Order order)
    {
        if (string.IsNullOrEmpty(order.Name))
            throw new BO.BlInvalidValueException("Order name cannot be empty.");

        if (!Tools.IsValidPhone(order.Phone))
            throw new BO.BlInvalidValueException("Invalid phone number.");

        if (string.IsNullOrEmpty(order.Addres))
            throw new BO.BlInvalidValueException("Order address cannot be empty.");

        if (string.IsNullOrEmpty(order.Details))
            throw new BO.BlInvalidValueException("Order details cannot be empty.");
    }

    /// <summary>
    /// Converts a data layer order to a business logic OrderInList object using pre-fetched deliveries.
    /// </summary>
    /// <param name="doOrder">The data layer order to convert.</param>
    /// <param name="deliveriesMap">Pre-fetched deliveries grouped by order ID.</param>
    /// <returns>An OrderInList object with calculated fields.</returns>
    private static BO.OrderInList s_convertToBoOrderOptimized(
        DO.Order doOrder,
        Dictionary<int, List<DO.Delivery>> deliveriesMap)
    {
        List<DO.Delivery> orderDeliveries = deliveriesMap.TryGetValue(doOrder.Id, out var deliveries)
            ? deliveries
            : [];

        DO.Delivery? latestDelivery = orderDeliveries.FirstOrDefault();
        var orderStatus = (BO.OrderStatus)doOrder.OrderStatus;
        double distanceKm = doOrder.DistanceKm ?? Tools.GetDistance(doOrder);

        return new BO.OrderInList
        {
            OrderId = doOrder.Id,
            DeliveryId = latestDelivery?.Id,
            TypeOfOrder = (BO.TypeOfOrder)doOrder.TypeOfOrder,
            DistanceKm = distanceKm,
            OrderStatus = orderStatus,
            ScheduleStatus = Tools.GetScheduleStatus(doOrder, latestDelivery),
            TimeLeftForDelivery = Tools.GetTimeLeftForDelivery(doOrder, orderStatus),
            TotalTimeOfDelivery = Tools.GetTotalTimeOfDelivery(doOrder, orderStatus, latestDelivery?.TimeEndDelivery),
            NumberOfDeliveryAttempts = orderDeliveries.Count
        };
    }

    /// <summary>
    /// Creates a list of all delivery attempts associated with a specific order.
    /// </summary>
    /// <param name="orderId">The unique identifier of the order.</param>
    /// <returns>
    /// A list of DeliveryPerOrderInList objects, or null if no deliveries exist.
    /// </returns>
    private static List<BO.DeliveryPerOrderInList>? s_createDeliveryPerOrderInList(int orderId)
    {
        var deliveries = from doDelivery in s_dal.Delivery.ReadAll(d => d.OrderId == orderId)
                         let courier = s_dal.Courier.Read(doDelivery.CourierId)
                         select new BO.DeliveryPerOrderInList
                         {
                             DeliveryId = doDelivery.Id,
                             CourierId = courier.Id,
                             CourierName = courier.Name,
                             TypeShipment = (BO.TheTypeShipment)courier.TypeShipment,
                             OrderDate = doDelivery.OrderDate,
                             EndDelivery = doDelivery.EndDelivery.HasValue
                                 ? (BO.EndDelivery)doDelivery.EndDelivery.Value
                                 : null,
                             TimeEndDelivery = doDelivery.TimeEndDelivery
                         };

        return deliveries.Any() ? [.. deliveries] : null;
    }

    /// <summary>
    /// Calculates the estimated delivery time for an order.
    /// </summary>
    /// <param name="doOrder">The data layer order.</param>
    /// <param name="deliveries">List of delivery attempts for the order.</param>
    /// <returns>The estimated delivery time, or null if not applicable.</returns>
    private static DateTime? s_calculateEstimatedDeliveryTime(
        DO.Order doOrder,
        List<BO.DeliveryPerOrderInList>? deliveries)
    {
        if (deliveries is not List<BO.DeliveryPerOrderInList> orderInProgresses)
            return null;

        var activeDelivery = orderInProgresses
            .OrderByDescending(d => d.DeliveryId)
            .FirstOrDefault(d => d.EndDelivery == null);

        return activeDelivery != null
            ? activeDelivery.OrderDate + Tools.GetEstimatedDeliveryTime(doOrder)
            : null;
    }

    /// <summary>
    /// Cancels an order that is in OPEN or REFUSED status.
    /// </summary>
    /// <param name="doOrder">The order to cancel.</param>
    private static void s_cancelOpenOrder(DO.Order doOrder)
    {
        doOrder = doOrder with { OrderStatus = DO.OrderStatus.CONCELLED };
        s_dal.Order.Update(doOrder);
        Observer.NotifyItemUpdated(doOrder.Id);

        DO.Delivery delivery = new DO.Delivery
        {
            Id = 0,
            OrderId = doOrder.Id,
            CourierId = 0,
            TypeShipment = DO.TheTypeShipment.FOOT,
            OrderDate = AdminManager.Now,
            EndDelivery = DO.EndDelivery.CONCELLED,
            TimeEndDelivery = AdminManager.Now,
            ActualDistance = 0
        };
        s_dal.Delivery.Create(delivery);
    }

    /// <summary>
    /// Cancels an order that is currently being delivered.
    /// </summary>
    /// <param name="doOrder">The order to cancel.</param>
    /// <param name="orderId">The order ID for notification purposes.</param>
    /// <exception cref="BO.BlDoesNotExistException">
    /// Thrown when the delivery or courier is not found.
    /// </exception>
    private static void s_cancelDeliveringOrder(DO.Order doOrder, int orderId)
    {
        doOrder = doOrder with { OrderStatus = DO.OrderStatus.CONCELLED };
        s_dal.Order.Update(doOrder);
        Observer.NotifyItemUpdated(doOrder.Id);

        var delivery = (from d in s_dal.Delivery.ReadAll()
                        where d.OrderId == doOrder.Id
                        orderby d.Id descending
                        select d).FirstOrDefault()
            ?? throw new BO.BlDoesNotExistException("Delivery not found for the order");

        s_dal.Delivery.Update(delivery with
        {
            EndDelivery = DO.EndDelivery.CONCELLED,
            TimeEndDelivery = AdminManager.Now
        });

        var courier = s_dal.Courier.Read(delivery.CourierId)
            ?? throw new BO.BlDoesNotExistException("Courier not found");

        try
        {
            Tools.SendEmail(
                courier.Email,
                "Order Cancelled",
                $"Order number {orderId} has been cancelled by the manager");
        }
        catch (SmtpException)
        {
            throw new SmtpException("Failed to send email notification");
        }
        finally
        {
            DeliveryManager.Observer.NotifyItemUpdated(delivery.Id);
            CourierManager.Observer.NotifyItemUpdated(delivery.CourierId);
            Observer.NotifyItemUpdated(orderId);
            Observer.NotifyListUpdated();
        }
    }

    /// <summary>
    /// Creates a filter predicate function based on the specified field and value.
    /// </summary>
    /// <param name="filter">The field to filter by, or null for no filtering.</param>
    /// <param name="filterValue">The value to match against the specified field.</param>
    /// <returns>A predicate function for filtering orders.</returns>
    /// <exception cref="BO.BlInvalidValueException">
    /// Thrown when a filter field is specified but no filter value is provided.
    /// </exception>
    private static Func<BO.OrderInList, bool> s_getFilterPredicate(
        BO.OrderInListField? filter,
        object? filterValue)
    {
        if (filter is not null && filterValue is null)
            throw new BO.BlInvalidValueException("Filter value must be provided when a filter field is specified.");

        return filter switch
        {
            BO.OrderInListField.OrderId => o => o.OrderId == (int)filterValue!,
            BO.OrderInListField.TypeOfOrder => o => o.TypeOfOrder == (BO.TypeOfOrder)filterValue!,
            BO.OrderInListField.OrderStatus => o => o.OrderStatus == (BO.OrderStatus)filterValue!,
            BO.OrderInListField.DistanceKm => o => o.DistanceKm == Convert.ToDouble(filterValue),
            BO.OrderInListField.ScheduleStatus => o => o.ScheduleStatus == (BO.ScheduleStatus)filterValue!,
            BO.OrderInListField.TimeLeftForDelivery => o => o.TimeLeftForDelivery <= (TimeSpan)filterValue!,
            BO.OrderInListField.TotalTimeOfDelivery => o => o.TotalTimeOfDelivery <= (TimeSpan)filterValue!,
            BO.OrderInListField.DeliveryAttempts => o => o.NumberOfDeliveryAttempts == (int)filterValue!,
            _ => _ => true
        };
    }

    /// <summary>
    /// Creates a sort selector function based on the specified field.
    /// </summary>
    /// <param name="sort">The field to sort by, or null to use default sorting.</param>
    /// <returns>A selector function that extracts the specified field value.</returns>
    private static Func<BO.OrderInList, object> s_getSortSelector(BO.OrderInListField? sort)
    {
        return sort switch
        {
            BO.OrderInListField.OrderId => o => o.OrderId,
            BO.OrderInListField.TypeOfOrder => o => o.TypeOfOrder,
            BO.OrderInListField.OrderStatus => o => o.OrderStatus,
            BO.OrderInListField.DistanceKm => o => o.DistanceKm,
            BO.OrderInListField.ScheduleStatus => o => o.ScheduleStatus,
            BO.OrderInListField.TimeLeftForDelivery => o => o.TimeLeftForDelivery,
            BO.OrderInListField.TotalTimeOfDelivery => o => o.TotalTimeOfDelivery,
            _ => o => o.OrderStatus
        };
    }

    /// <summary>
    /// Sorts closed deliveries by the specified field.
    /// </summary>
    /// <param name="query">The query to sort.</param>
    /// <param name="sort">The field to sort by.</param>
    /// <returns>Sorted enumerable of closed deliveries.</returns>
    private static IEnumerable<BO.ClosedDeliveryInList> s_sortClosedDeliveries(
        IEnumerable<BO.ClosedDeliveryInList> query,
        BO.ClosedDeliveryInListField? sort)
