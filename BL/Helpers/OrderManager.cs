    /// <summary>
    /// Creates a filter predicate function based on the specified field and value.
    /// </summary>
    /// <param name="filter">The field to filter by, or null for no filtering.</param>
    /// <param name="filterValue">The value to match against the specified field.</param>
    /// <returns>
    /// A predicate function that returns true if the order matches the filter criteria,
    /// or always returns true if no filter is specified.
    /// </returns>
    /// <exception cref="BO.BlInvalidValueException">Thrown when a filter field is specified but no filter value is provided.</exception>
    /// <remarks>
    /// Supports filtering by OrderId, TypeOfOrder, OrderStatus, DistanceKm, ScheduleStatus,
    /// TimeLeftForDelivery (less than or equal), TotalTimeOfDelivery (less than or equal),
    /// and DeliveryAttempts.
    /// </remarks>
    private static Func<BO.OrderInList, bool> s_getFilterFunc(BO.OrderInListField? filter, Object? filterValue)
    {
        if (filter is not null && filterValue is null)
            throw new BO.BlInvalidValueException("Filter value must be provided when a filter field is specified.");
        return filter switch
        {
            BO.OrderInListField.OrderId => (o) => o.OrderId == (int)filterValue!,
            BO.OrderInListField.TypeOfOrder => (o) => o.TypeOfOrder == (BO.TypeOfOrder)filterValue!,
            BO.OrderInListField.OrderStatus => (o) => o.OrderStatus == (BO.OrderStatus)filterValue!,
            BO.OrderInListField.DistanceKm => (o) => o.DistanceKm == Convert.ToDouble(filterValue),
            BO.OrderInListField.ScheduleStatus => (o) => o.ScheduleStatus == (BO.ScheduleStatus)filterValue!,
            BO.OrderInListField.TimeLeftForDelivery => (o) => o.TimeLeftForDelivery <= (TimeSpan)filterValue!,
            BO.OrderInListField.TotalTimeOfDelivery => (o) => o.TotalTimeOfDelivery <= (TimeSpan)filterValue!,
            BO.OrderInListField.DeliveryAttempts => (o) => o.NumberOfDeliveryAttempts == (int)filterValue!,
            _ => (o) => true
        };
    }

    /// <summary>
    /// Creates a sort selector function based on the specified field.
    /// </summary>
    /// <param name="sort">The field to sort by, or null to use default sorting.</param>
    /// <returns>
    /// A selector function that extracts the specified field value from an OrderInList object,
    /// or extracts OrderStatus if no sort field is specified.
    /// </returns>
    /// <remarks>
    /// Supports sorting by OrderId, TypeOfOrder, OrderStatus, DistanceKm, ScheduleStatus,
    /// TimeLeftForDelivery, and TotalTimeOfDelivery. Default sort is by OrderStatus.
    /// </remarks>
    private static Func<BO.OrderInList, Object> s_getSortFunc(BO.OrderInListField? sort)
    {
        return sort switch
        {
            BO.OrderInListField.OrderId => (o) => o.OrderId,
            BO.OrderInListField.TypeOfOrder => (o) => o.TypeOfOrder,
            BO.OrderInListField.OrderStatus => (o) => o.OrderStatus,
            BO.OrderInListField.DistanceKm => (o) => o.DistanceKm,
            BO.OrderInListField.ScheduleStatus => (o) => o.ScheduleStatus,
            BO.OrderInListField.TimeLeftForDelivery => (o) => o.TimeLeftForDelivery,
            BO.OrderInListField.TotalTimeOfDelivery => (o) => o.TotalTimeOfDelivery,
            _ => (o) => o.OrderStatus
        };
    }

    /// <summary>
    /// Creates a list of all delivery attempts associated with a specific order.
    /// </summary>
    /// <param name="orderId">The unique identifier of the order.</param>
    /// <returns>
    /// A list of DeliveryPerOrderInList objects containing details about each delivery attempt,
    /// or null if no deliveries have been attempted for this order.
    /// </returns>
    /// <remarks>
    /// Each delivery record includes the assigned courier information, shipment type,
    /// timing details, and outcome status. This provides a complete history of all
    /// delivery attempts for the order.
    /// </remarks>
    private static List<BO.DeliveryPerOrderInList>? s_createDeliveryPerOrderInList(int orderId)
    {
        var deliveries = from doDelivery in s_dal.Delivery.ReadAll(d => d.OrderId == orderId)
                         let courier = s_dal.Courier.Read(doDelivery.CourierId)
                         select new BO.DeliveryPerOrderInList
                         {
                             DeliveryId = doDelivery.Id,
                             CourierId = courier.Id,
                             CourierName = courier.Name,
                             TypeShipment = (BO.TheTypeShipment)courier.TypeShipment,
                             OrderDate = doDelivery.OrderDate,
                             EndDelivery = doDelivery.EndDelivery.HasValue ? (BO.EndDelivery)doDelivery.EndDelivery.Value : null,
                             TimeEndDelivery = doDelivery.TimeEndDelivery.HasValue ? doDelivery.TimeEndDelivery.Value : null
                         }
        ;
        return deliveries.Any() ? [.. deliveries] : null;
    }

