    /// <summary>
    /// Retrieves all completed deliveries for a specific courier with optional filtering and sorting.
    /// </summary>
    /// <param name="courierId">The unique identifier of the courier.</param>
    /// <param name="filter">Optional filter for order type, or null to include all types.</param>
    /// <param name="sort">The field to sort the results by.</param>
    /// <returns>
    /// A list of closed delivery records showing delivery outcomes, distances, times, and final statuses.
    /// Results are filtered to show only one delivery per order (the most recent).
    /// </returns>
    /// <remarks>
    /// Only returns deliveries that have ended (EndDelivery is not null).
    /// Results are deduplicated by OrderId to show only the most recent delivery attempt for each order.
    /// </remarks>
    public static List<BO.ClosedDeliveryInList> GetClosed(int courierId, BO.TypeOfOrder? filter, BO.ClosedDeliveryInListField? sort)
    {
        var query = from doDelivery in s_dal.Delivery.ReadAll(d => d.CourierId == courierId && d.EndDelivery != null)
                    let order = s_dal.Order.Read(doDelivery.OrderId)
                    where order != null && (filter == null || (BO.TypeOfOrder)order.TypeOfOrder == filter)
                    select new BO.ClosedDeliveryInList
                    {
                        DeliveryId = doDelivery.Id,
                        OrderId = order.Id,
                        OrderType = (BO.TypeOfOrder)order.TypeOfOrder,
                        Address = order.Addres,
                        ShipmentType = (BO.TheTypeShipment)doDelivery.TypeShipment,
                        ActualDistens = doDelivery.ActualDistance,
                        DelyveryTime = (TimeSpan)(doDelivery.TimeEndDelivery! - doDelivery.OrderDate),
                        EndDelivery = (BO.EndDelivery)doDelivery.EndDelivery!
                    };
        var uniqueQuery = query.DistinctBy(x => x.OrderId);

        IEnumerable<BO.ClosedDeliveryInList> sortedQuery = sort switch
        {
            BO.ClosedDeliveryInListField.DeliveryId => uniqueQuery.OrderBy(x => x.DeliveryId),
            BO.ClosedDeliveryInListField.OrderId => uniqueQuery.OrderBy(x => x.OrderId),
            BO.ClosedDeliveryInListField.TypeOfOrder => uniqueQuery.OrderBy(x => x.OrderType),
            BO.ClosedDeliveryInListField.Address => uniqueQuery.OrderBy(x => x.Address),
            BO.ClosedDeliveryInListField.ShipmentType => uniqueQuery.OrderBy(x => x.ShipmentType),
            BO.ClosedDeliveryInListField.AqualDistens => uniqueQuery.OrderBy(x => x.ActualDistens),
            BO.ClosedDeliveryInListField.DelyveryTime => uniqueQuery.OrderBy(x => x.DelyveryTime),
            BO.ClosedDeliveryInListField.EndDelivery => uniqueQuery.OrderBy(x => x.EndDelivery),
            _ => uniqueQuery.OrderBy(x => x.OrderType) // ברירת מחדל
        };

        return [.. sortedQuery];
    }

    /// <summary>
    /// Retrieves all open orders available for a specific courier to deliver.
    /// </summary>
    /// <param name="courierId">The unique identifier of the courier.</param>
    /// <param name="filter">Optional filter for order type, or null to include all types.</param>
    /// <param name="sort">The field to sort the results by.</param>
    /// <returns>
    /// A list of open orders within the courier's maximum delivery distance,
    /// including distance calculations, time constraints, and schedule status.
    /// </returns>
    /// <exception cref="BO.BlDoesNotExistException">Thrown when the courier is not found.</exception>
    /// <remarks>
    /// Only returns orders with OPEN or REFUSED status that are within the courier's
    /// maximum delivery distance capability. Results can be filtered by order type and
    /// sorted by various fields.
    /// </remarks>
    public static List<BO.OpenOrderInList> GetOpen(int courierId, BO.TypeOfOrder? filter, BO.OpenOrderInListField? sort)
    {
        DO.Courier doCourier = s_dal.Courier.Read(courierId)
            ?? throw new BO.BlDoesNotExistException("Courier not found");

        IEnumerable<DO.TypeOfOrder> permittedOrders = doCourier.TypeShipment switch
        {
            DO.TheTypeShipment.BIKE or DO.TheTypeShipment.FOOT =>
                new[] { DO.TypeOfOrder.STANDART },

            DO.TheTypeShipment.CAR =>
                new[] { DO.TypeOfOrder.STANDART, DO.TypeOfOrder.FAST_DELIVERY },

            DO.TheTypeShipment.MOTORCYCLE =>
                new[] { DO.TypeOfOrder.STANDART, DO.TypeOfOrder.FAST_DELIVERY, DO.TypeOfOrder.DELIVER_IMMEDIATELY },

            _ => Array.Empty<DO.TypeOfOrder>() // ברירת מחדל ליתר ביטחון
        };

        Func<DO.Order, bool> toFilter = (order) =>
        {
            // בדיקה א': האם השליח בכלל יכול לקחת הזמנה כזו?
            bool isAllowedForCourier = permittedOrders.Contains(order.TypeOfOrder);

            // בדיקה ב': האם זה תואם לפילטר שהמשתמש ביקש? (אם הפילטר ריק - הכל עובר)
            bool matchesUserRequest = (filter == null) || (order.TypeOfOrder == (DO.TypeOfOrder)filter);

            // מחזירים אמת רק אם שני התנאים מתקיימים
            return isAllowedForCourier && matchesUserRequest;
        };

        var query = from doOrder in s_dal.Order.ReadAll(o => o.OrderStatus == DO.OrderStatus.OPEN)
                    let distense = Tools.GetActualDistance(doOrder.Addres, (BO.TheTypeShipment)doCourier.TypeShipment)
                    where (toFilter(doOrder) && (distense <= doCourier.MaxDistanceDelivery))
                    select new BO.OpenOrderInList
                    {
                        OrderId = doOrder.Id,
                        TypeOfOrder = (BO.TypeOfOrder)doOrder.TypeOfOrder,
                        Weight = doOrder.Weight,
                        Address = doOrder.Addres,
                        DistanceKm = doOrder.DistanceKm ?? 0,
                        ActualDistance = distense,
                        EstimatedDeliveryTime = null,
                        ScheduleStatus = Tools.GetScheduleStatus(doOrder),
                        TimeLeftForDelivery = Tools.GetTimeLeftForDelivery(doOrder),
                        MaxDeliveryTime = doOrder.OrderDate + AdminManager.GetConfig().MaxDeliveryTime
                    };

        IEnumerable<BO.OpenOrderInList> sortedQuery = sort switch
        {
            BO.OpenOrderInListField.OrderId => query.OrderBy(x => x.OrderId),
